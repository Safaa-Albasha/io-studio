#!/usr/bin/env node
// I/O Studio — مكتبة التصميم الداخلي + جسر Blender.
// الاستخدام:
//   node engine/interior.js list-styles | list-rooms | list-furniture [--category seating]
//   node engine/interior.js new <room-preset> --style <id> --out room.json
//   node engine/interior.js restyle room.json --style <id>
//   node engine/interior.js validate room.json
//   node engine/interior.js scene room.json [--format 9:16] [--variant before] [--out scene.json]
//   node engine/interior.js dry-run room.json            (يطبع شجرة المشهد بدون Blender)
//   node engine/interior.js build room.json [--blend out.blend]
//   node engine/interior.js render room.json --format 9:16|16:9|3:4 [--engine eevee|cycles] [--samples 32] [--shots wide,detail] [--out dir]
//   node engine/interior.js walkthrough room.json --seconds 8 [--format 9:16] [--engine …] [--samples …]
//   node engine/interior.js before-after room.json [--format 9:16] [--shot wide]
//   node engine/interior.js preview [room.json] [--port 4790]   (معاينة المتصفح بدون Blender)
//   node engine/interior.js bundle                       (يحدّث library/interiors/bundle.js للمتصفح)
//   node engine/interior.js where-blender
'use strict';
const fs = require('fs');
const path = require('path');
const { spawnSync, spawn } = require('child_process');
const Core = require('./blender/room-core.js');

const ROOT = path.resolve(__dirname, '..');
const LIB_DIR = path.join(ROOT, 'library', 'interiors');
const BLENDER_DIR = path.join(__dirname, 'blender');

// ───────── المكتبة ─────────
function readJSON(f) { return JSON.parse(fs.readFileSync(f, 'utf8')); }
function readDir(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => readJSON(path.join(dir, f)));
}
function loadLibrary(dir = LIB_DIR) {
  return Core.libraryFrom({
    styles: readDir(path.join(dir, 'styles')),
    catalog: readJSON(path.join(dir, 'furniture', 'catalog.json')),
    materials: readJSON(path.join(dir, 'materials.json')),
    rooms: readDir(path.join(dir, 'rooms')),
  });
}
function bundleSource(lib) {
  const data = {
    styles: Object.values(lib.styles),
    catalog: Object.values(lib.catalog),
    materials: lib.materials,
    rooms: Object.values(lib.rooms),
  };
  return '// Generated by `node engine/interior.js bundle` — do not edit. مكتبة التصميم الداخلي للمتصفح.\n'
    + 'window.IO_INTERIORS = ' + JSON.stringify(data) + ';\n';
}

// ───────── إيجاد Blender (دالة صافية: كل الوصول للنظام يجي من برّا) ─────────
function versionKey(name) {
  const m = String(name).match(/(\d+)(?:\.(\d+))?(?:\.(\d+))?/);
  return m ? [+m[1], +(m[2] || 0), +(m[3] || 0)] : [0, 0, 0];
}
function byVersionDesc(a, b) {
  const x = versionKey(a), y = versionKey(b);
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return y[i] - x[i];
  return 0;
}
function blenderCandidates({ platform, env = {}, readdir = () => [], home = '' }) {
  const out = [];
  const win = platform === 'win32';
  const join = win ? (...p) => p.join('\\').replace(/\\+/g, '\\') : (...p) => p.join('/').replace(/\/+/g, '/');
  for (const k of ['IO_BLENDER', 'BLENDER_PATH', 'BLENDER']) if (env[k]) out.push({ path: env[k], source: `env:${k}` });
  const sep = win ? ';' : ':';
  const exe = win ? 'blender.exe' : 'blender';
  for (const dir of String(env.PATH || env.Path || '').split(sep).filter(Boolean)) out.push({ path: join(dir, exe), source: 'PATH' });
  const safeReaddir = (d) => { try { return readdir(d) || []; } catch { return []; } };
  if (win) {
    const bases = [env.ProgramFiles || 'C:\\Program Files', env['ProgramFiles(x86)'] || 'C:\\Program Files (x86)'];
    if (env.LOCALAPPDATA) bases.push(join(env.LOCALAPPDATA, 'Programs'));
    for (const base of bases) {
      const foundation = join(base, 'Blender Foundation');
      const vers = safeReaddir(foundation).filter((n) => /^blender/i.test(n)).sort(byVersionDesc);
      for (const v of vers) out.push({ path: join(foundation, v, 'blender.exe'), source: 'Program Files' });
    }
    out.push({ path: 'C:\\Program Files (x86)\\Steam\\steamapps\\common\\Blender\\blender.exe', source: 'Steam' });
  } else if (platform === 'darwin') {
    out.push({ path: '/Applications/Blender.app/Contents/MacOS/Blender', source: 'Applications' });
    for (const n of safeReaddir('/Applications').filter((n) => /^Blender.*\.app$/i.test(n) && n !== 'Blender.app').sort(byVersionDesc)) {
      out.push({ path: `/Applications/${n}/Contents/MacOS/Blender`, source: 'Applications' });
    }
    if (home) out.push({ path: join(home, 'Applications/Blender.app/Contents/MacOS/Blender'), source: '~/Applications' });
    out.push({ path: '/opt/homebrew/bin/blender', source: 'brew' });
  } else {
    out.push({ path: '/usr/bin/blender', source: 'apt' }, { path: '/usr/local/bin/blender', source: 'local' });
    out.push({ path: '/snap/bin/blender', source: 'snap' });
    out.push({ path: '/var/lib/flatpak/exports/bin/org.blender.Blender', source: 'flatpak' });
    if (home) out.push({ path: join(home, '.local/share/flatpak/exports/bin/org.blender.Blender'), source: 'flatpak (user)' });
    for (const base of ['/opt', home].filter(Boolean)) {
      for (const n of safeReaddir(base).filter((n) => /^blender/i.test(n)).sort(byVersionDesc)) out.push({ path: join(base, n, 'blender'), source: 'portable' });
    }
  }
  return out;
}
function findBlender(opts) {
  const exists = opts.exists || (() => false);
  for (const c of blenderCandidates(opts)) {
    try { if (exists(c.path)) return c; } catch { /* تجاهل */ }
  }
  return null;
}
function installHint(platform) {
  if (platform === 'win32') return 'winget install --id BlenderFoundation.Blender -e';
  if (platform === 'darwin') return 'brew install --cask blender';
  return 'sudo snap install blender --classic   (أو: sudo apt install blender)';
}
function systemBlender() {
  return findBlender({
    platform: process.platform, env: process.env, home: require('os').homedir(),
    exists: (p) => { try { return fs.statSync(p).isFile(); } catch { return false; } },
    readdir: (d) => fs.readdirSync(d),
  });
}
function needBlender() {
  const b = systemBlender();
  if (b) return b.path;
  console.error([
    '✗ ما لگيت Blender على هالجهاز.',
    '  Blender مجاني ومفتوح المصدر. نصّبه بأمر واحد:',
    `    ${installHint(process.platform)}`,
    '  أو خلي الدكتور يسويها: node engine/doctor.js --install --only blender',
    '  وإذا منصّب بمكان غريب: حط المسار بمتغيّر IO_BLENDER.',
    '  تگدر هسه تعاين الغرفة بالمتصفح بدون Blender: node engine/interior.js preview room.json',
  ].join('\n'));
  process.exit(3);
}

// ───────── أدوات CLI ─────────
function parseArgs(argv) {
  const pos = [], flags = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const k = a.slice(2);
      if (i + 1 < argv.length && !argv[i + 1].startsWith('--')) flags[k] = argv[++i];
      else flags[k] = true;
    } else pos.push(a);
  }
  return { pos, flags };
}
function loadRoom(file) {
  if (!file) { console.error('✗ حدد ملف room.json'); process.exit(2); }
  try { return readJSON(path.resolve(file)); } catch (e) { console.error(`✗ ما گدرت أقرا ${file}: ${e.message}`); process.exit(2); }
}
function report(res) {
  for (const e of res.errors) console.log('  ✗ ' + e);
  for (const w of res.warnings) console.log('  ⚠ ' + w);
}
function mustValidate(room, lib) {
  const res = Core.validateRoom(room, lib);
  if (res.errors.length) { console.log('الغرفة بيها أخطاء:'); report(res); process.exit(1); }
  if (res.warnings.length) { console.log('ملاحظات:'); report(res); }
}
function writeScene(room, lib, opts, outFile) {
  const scene = Core.resolveScene(room, lib, opts);
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, JSON.stringify(scene));
  return scene;
}
function runBlender(script, args, { blendFile } = {}) {
  const bin = needBlender();
  const full = ['-b'].concat(blendFile ? [blendFile] : [], ['--factory-startup', '-noaudio', '-P', path.join(BLENDER_DIR, script), '--'], args);
  console.log(`▶ ${path.basename(bin)} ${full.map((a) => (/\s/.test(a) ? JSON.stringify(a) : a)).join(' ')}`);
  const r = spawnSync(bin, full, { encoding: 'utf8', maxBuffer: 1 << 28 });
  const out = (r.stdout || '') + (r.stderr || '');
  for (const l of out.split('\n')) if (/^(IO |Error|Traceback|  File|\w+Error)/.test(l)) console.log(l);
  const ok = r.status === 0 && !/^IO ERROR/m.test(out);
  return { ok, out, status: r.status };
}
function outDirFor(roomFile, flags, sub) {
  const base = flags.out ? path.resolve(flags.out) : path.join(path.dirname(path.resolve(roomFile)), path.basename(roomFile, '.json') + '-renders');
  return sub ? path.join(base, sub) : base;
}
function engineFlags(flags) {
  const engine = (flags.engine || 'eevee').toLowerCase();
  if (!['eevee', 'cycles'].includes(engine)) { console.error('✗ --engine لازم eevee أو cycles'); process.exit(2); }
  const samples = flags.samples ? Math.max(1, parseInt(flags.samples, 10)) : (engine === 'cycles' ? 64 : 32);
  const scale = flags.scale ? Math.min(100, Math.max(10, parseInt(flags.scale, 10))) : 0;
  return { engine, samples, scale };
}
// إذا EEVEE فشل (أجهزة بدون كرت شاشة/سيرفرات) نعيد بـ Cycles
function renderWithFallback(script, args, eng, extra) {
  if (eng.scale) args = args.concat(['--scale', String(eng.scale)]);
  let r = runBlender(script, args.concat(['--engine', eng.engine, '--samples', String(eng.samples)]), extra);
  if (!r.ok && eng.engine === 'eevee') {
    console.log('⚠ EEVEE ما اشتغل على هالجهاز (يحتاج كرت شاشة/OpenGL). أعيد بـ Cycles…');
    r = runBlender(script, args.concat(['--engine', 'cycles', '--samples', String(Math.min(eng.samples, 32))]), extra);
  }
  if (!r.ok) { console.error('✗ Blender فشل. آخر السطور:\n' + r.out.split('\n').slice(-25).join('\n')); process.exit(1); }
  return r;
}

// ───────── الأوامر ─────────
function main(argv) {
  const [cmd, ...rest] = argv;
  const { pos, flags } = parseArgs(rest);
  const lib = loadLibrary();
  switch (cmd) {
    case 'list-styles':
      for (const s of Object.values(lib.styles)) console.log(`${s.id.padEnd(18)} ${s.name_ar}  —  ${s.description_ar.split('.')[0].slice(0, 70)}`);
      return;
    case 'list-rooms':
      for (const r of Object.values(lib.rooms)) console.log(`${r.id.padEnd(18)} ${r.name_ar} (${r.room.width}×${r.room.depth} م، ستايل ${r.style})`);
      return;
    case 'list-furniture': {
      const items = Object.values(lib.catalog).filter((i) => !flags.category || i.category === flags.category);
      for (const i of items) console.log(`${i.id.padEnd(22)} ${i.category.padEnd(11)} ${i.size.join('×')} م  ${i.name_ar}`);
      console.log(`(${items.length} قطعة)`);
      return;
    }
    case 'new': {
      const preset = pos[0];
      if (!preset || !lib.rooms[preset]) { console.error(`✗ اختار قالب: ${Object.keys(lib.rooms).join(', ')}`); process.exit(2); }
      const style = flags.style || lib.rooms[preset].style;
      if (!lib.styles[style]) { console.error(`✗ ستايل غير معروف. المتوفر: ${Object.keys(lib.styles).join(', ')}`); process.exit(2); }
      const room = Core.newFromPreset(preset, style, lib);
      const out = path.resolve(flags.out || 'room.json');
      fs.writeFileSync(out, JSON.stringify(room, null, 2) + '\n');
      console.log(`✓ ${lib.rooms[preset].name_ar} بستايل ${lib.styles[style].name_ar} → ${out}`);
      const res = Core.validateRoom(room, lib);
      if (res.errors.length || res.warnings.length) report(res);
      return;
    }
    case 'restyle': {
      const file = pos[0]; const room = loadRoom(file);
      if (!lib.styles[flags.style]) { console.error(`✗ --style لازم واحد من: ${Object.keys(lib.styles).join(', ')}`); process.exit(2); }
      const out = Core.applyStyle(room, flags.style, lib);
      fs.writeFileSync(path.resolve(flags.out || file), JSON.stringify(out, null, 2) + '\n');
      console.log(`✓ صار الستايل ${lib.styles[flags.style].name_ar}`);
      return;
    }
    case 'validate': {
      const room = loadRoom(pos[0]);
      const res = Core.validateRoom(room, lib);
      if (!res.errors.length) console.log(`✓ ${pos[0]} سليم${res.warnings.length ? ` (${res.warnings.length} ملاحظة)` : ''}`);
      report(res);
      process.exitCode = res.errors.length ? 1 : 0;
      return;
    }
    case 'scene': {
      const room = loadRoom(pos[0]); mustValidate(room, lib);
      const scene = Core.resolveScene(room, lib, { format: flags.format, variant: flags.variant });
      const txt = JSON.stringify(scene, null, flags.pretty ? 1 : 0);
      if (flags.out) { fs.writeFileSync(path.resolve(flags.out), txt); console.log(`✓ ${flags.out}`); } else process.stdout.write(txt + '\n');
      return;
    }
    case 'dry-run': {
      const room = loadRoom(pos[0]); mustValidate(room, lib);
      const tmp = path.join(require('os').tmpdir(), `io-scene-${process.pid}.json`);
      writeScene(room, lib, { format: flags.format }, tmp);
      const py = process.platform === 'win32' ? 'python' : 'python3';
      const r = spawnSync(py, [path.join(BLENDER_DIR, 'build_room.py'), '--dry-run', '--scene', tmp], { stdio: 'inherit' });
      fs.rmSync(tmp, { force: true });
      process.exitCode = r.status || 0;
      return;
    }
    case 'build': {
      const file = pos[0]; const room = loadRoom(file); mustValidate(room, lib);
      const blend = path.resolve(flags.blend || file.replace(/\.json$/, '') + '.blend');
      const sceneFile = blend.replace(/\.blend$/, '') + '.scene.json';
      writeScene(room, lib, { format: flags.format }, sceneFile);
      const eng = engineFlags(flags);
      const r = runBlender('build_room.py', ['--scene', sceneFile, '--blend', blend, '--engine', eng.engine, '--samples', String(eng.samples)]);
      if (!r.ok) { console.error(r.out.split('\n').slice(-25).join('\n')); process.exit(1); }
      console.log(`✓ ملف Blender: ${blend}`);
      return;
    }
    case 'render': {
      const file = pos[0]; const room = loadRoom(file); mustValidate(room, lib);
      const fmt = Core.normFormat(flags.format || '9:16');
      if (!fmt) { console.error('✗ --format لازم 9:16 أو 16:9 أو 3:4'); process.exit(2); }
      const out = outDirFor(file, flags, fmt.replace(':', 'x'));
      const sceneFile = path.join(out, 'scene.json');
      writeScene(room, lib, { format: fmt }, sceneFile);
      const args = ['--scene', sceneFile, '--format', fmt, '--out', out];
      if (flags.shots) args.push('--shots', String(flags.shots));
      if (flags.blend) args.push('--blend', path.resolve(flags.blend));
      renderWithFallback('render.py', args, engineFlags(flags));
      console.log(`✓ الصور بـ ${out}`);
      return;
    }
    case 'walkthrough': {
      const file = pos[0]; const room = loadRoom(file); mustValidate(room, lib);
      const fmt = Core.normFormat(flags.format || '9:16');
      if (flags.seconds) { room.cameras = room.cameras || {}; room.cameras.walkthrough = Object.assign({}, room.cameras.walkthrough, { seconds: +flags.seconds }); }
      if (flags.fps) { room.cameras = room.cameras || {}; room.cameras.walkthrough = Object.assign({}, room.cameras.walkthrough, { fps: +flags.fps }); }
      const out = outDirFor(file, flags, 'walkthrough-' + fmt.replace(':', 'x'));
      const sceneFile = path.join(out, 'scene.json');
      writeScene(room, lib, { format: fmt }, sceneFile);
      const eng = engineFlags(flags);
      if (!flags.samples) eng.samples = 16;
      const args = ['--scene', sceneFile, '--format', fmt, '--out', out, '--animation'];
      if (flags.frames) args.push('--frames', String(flags.frames));
      renderWithFallback('render.py', args, eng);
      console.log(`✓ فيديو الجولة: ${path.join(out, 'walkthrough.mp4')}`);
      return;
    }
    case 'before-after': {
      const file = pos[0]; const room = loadRoom(file); mustValidate(room, lib);
      const fmt = Core.normFormat(flags.format || '9:16');
      const out = outDirFor(file, flags, 'before-after-' + fmt.replace(':', 'x'));
      const after = path.join(out, 'scene-after.json'), before = path.join(out, 'scene-before.json');
      writeScene(room, lib, { format: fmt }, after);
      writeScene(room, lib, { format: fmt, variant: 'before' }, before);
      const args = ['--before', before, '--after', after, '--format', fmt, '--out', out];
      if (flags.shot) args.push('--shot', String(flags.shot));
      if (flags.seconds) args.push('--seconds', String(flags.seconds));
      renderWithFallback('before_after.py', args, engineFlags(flags));
      console.log(`✓ قبل/بعد: ${out} (before.png, after.png, before_after.mp4)`);
      return;
    }
    case 'bundle': {
      const f = path.join(LIB_DIR, 'bundle.js');
      fs.writeFileSync(f, bundleSource(lib));
      console.log(`✓ ${path.relative(ROOT, f)} (${Object.keys(lib.styles).length} ستايل، ${Object.keys(lib.catalog).length} قطعة، ${Object.keys(lib.rooms).length} غرفة)`);
      return;
    }
    case 'preview': return preview(pos[0], flags, lib);
    case 'where-blender': {
      const b = systemBlender();
      if (b) console.log(`✓ Blender: ${b.path} (${b.source})`);
      else { console.log(`✗ ماكو Blender. نصّبه: ${installHint(process.platform)}  أو: node engine/doctor.js --install --only blender`); process.exitCode = 3; }
      return;
    }
    default:
      console.log(fs.readFileSync(__filename, 'utf8').split('\n').slice(1, 17).map((l) => l.replace(/^\/\/ ?/, '')).join('\n'));
      process.exitCode = cmd ? 2 : 0;
  }
}

// معاينة: سيرفر صغير من جذر البلگن حتى الصفحة توصل للمكتبة و room-core.js
function preview(roomFile, flags, lib) {
  const http = require('http');
  fs.writeFileSync(path.join(LIB_DIR, 'bundle.js'), bundleSource(lib));
  const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.json': 'application/json; charset=utf-8', '.png': 'image/png', '.css': 'text/css' };
  const roomPath = roomFile ? path.resolve(roomFile) : null;
  const srv = http.createServer((req, res) => {
    const u = new URL(req.url, 'http://x');
    if (u.pathname === '/user-room.json' && roomPath) {
      res.writeHead(200, { 'content-type': TYPES['.json'], 'cache-control': 'no-store' });
      return res.end(fs.readFileSync(roomPath));
    }
    if (u.pathname === '/save-room' && req.method === 'POST' && roomPath) {
      let body = ''; req.on('data', (c) => { body += c; if (body.length > 5e6) req.destroy(); });
      req.on('end', () => {
        try { const r = JSON.parse(body); fs.writeFileSync(roomPath, JSON.stringify(r, null, 2) + '\n'); res.writeHead(200); res.end('ok'); console.log(`✓ انحفظ ${roomPath}`); } catch (e) { res.writeHead(400); res.end(e.message); }
      });
      return undefined;
    }
    const p = path.normalize(decodeURIComponent(u.pathname)).replace(/^([/\\])+/, '');
    const file = path.join(ROOT, p || 'web/interior.html');
    if (!file.startsWith(ROOT)) { res.writeHead(403); return res.end(); }
    fs.readFile(file, (err, data) => {
      if (err) { res.writeHead(404); return res.end('مو موجود'); }
      res.writeHead(200, { 'content-type': TYPES[path.extname(file)] || 'application/octet-stream', 'cache-control': 'no-store' });
      res.end(data);
    });
    return undefined;
  });
  const port = +(flags.port || 4790);
  srv.listen(port, '127.0.0.1', () => {
    const url = `http://localhost:${port}/web/interior.html${roomPath ? '?room=/user-room.json' : ''}`;
    console.log(`معاينة الغرفة شغّالة: ${url}\n(Ctrl+C للإيقاف)`);
    if (flags.open) {
      const opener = process.platform === 'win32' ? ['cmd', ['/c', 'start', '', url]] : process.platform === 'darwin' ? ['open', [url]] : ['xdg-open', [url]];
      try { spawn(opener[0], opener[1], { stdio: 'ignore', detached: true }).unref(); } catch { /* تجاهل */ }
    }
  });
}

module.exports = { loadLibrary, bundleSource, blenderCandidates, findBlender, installHint, versionKey, LIB_DIR };
if (require.main === module) main(process.argv.slice(2));
