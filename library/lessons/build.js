#!/usr/bin/env node
/*
 * Rebuilds catalog.json and lessons.js (the bundle web/lessons.html loads) from
 * the lesson files in this folder. Run after adding or editing a lesson:
 *   node library/lessons/build.js
 * Each lesson keeps its library metadata in "meta": { id, subject, subjectLabel, level, stage }.
 * level is a free label ("ابتدائي ٣–٤"); stage is one of STAGES so the gallery can group by age.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const SS = require('../../web/lib/scene-core.js');

const DIR = __dirname;
const STAGES = { kindergarten: 'روضة وأطفال', primary: 'ابتدائي', middle: 'متوسط', secondary: 'إعدادي', adults: 'كبار وصنّاع محتوى' };
const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.json') && f !== 'catalog.json').sort();
const lessons = [], scenes = {}, problems = [];
for (const file of files) {
  const raw = JSON.parse(fs.readFileSync(path.join(DIR, file), 'utf8'));
  const { scene, errors } = SS.normalizeScene(raw);
  if (errors.length) problems.push(`${file}:\n  - ${errors.join('\n  - ')}`);
  const m = raw.meta || {};
  const id = m.id || file.replace(/\.json$/, '');
  if (!STAGES[m.stage]) problems.push(`${file}:\n  - meta.stage: واحد من ${Object.keys(STAGES).join('، ')}`);
  lessons.push({
    id, file, title: scene.title, subject: m.subject || 'other', subjectLabel: m.subjectLabel || 'أخرى', level: m.level || '',
    stage: m.stage || '', stageLabel: STAGES[m.stage] || '',
    style: scene.style, format: scene.format, duration: Math.round(SS.totalDuration(scene) * 10) / 10, beats: scene.beats.length,
    kinds: [...new Set(scene.beats.flatMap((b) => Object.keys(b).filter((k) => SS.BOARD_KINDS.includes(k) && !(k === 'label' && typeof b.label === 'string'))))],
  });
  scenes[id] = raw;
}
if (problems.length) { console.error('دروس بيها أخطاء:\n' + problems.join('\n')); process.exit(1); }
const catalog = { version: 1, count: lessons.length, stages: STAGES, lessons };
fs.writeFileSync(path.join(DIR, 'catalog.json'), JSON.stringify(catalog, null, 2) + '\n');
fs.writeFileSync(path.join(DIR, 'lessons.js'), '/* Generated by build.js — do not edit. */\nwindow.IO_LESSONS = ' + JSON.stringify({ catalog, scenes }) + ';\n');
console.log(`✓ ${lessons.length} درس — catalog.json و lessons.js`);
